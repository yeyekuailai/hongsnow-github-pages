window.populateResortSelect = function populateResortSelect(select, includeAll = true, filters = {}) {
  if (!select) return;
  const isEnglish = window.SNOWLINK_LOCALE === "en";
  const current = select.value;
  select.innerHTML = includeAll
    ? `<option value="all">${isEnglish ? "All U.S. resorts" : "全部美国雪场"}</option>`
    : `<option value="">${isEnglish ? "Select your resort" : "请选择所属雪场"}</option>`;

  ["epic", "ikon"].forEach((pass) => {
    const group = document.createElement("optgroup");
    group.label = pass === "epic" ? "Epic Pass · 美国" : "Ikon Pass · 美国";
    window.SNOWLINK_RESORTS
      .filter((resort) => resort.pass === pass)
      .filter((resort) => !filters.pass || filters.pass === "all" || resort.pass === filters.pass)
      .filter((resort) => !filters.state || filters.state === "all" || resort.state.split(" / ").includes(filters.state))
      .sort((a, b) => a.state.localeCompare(b.state) || a.name.localeCompare(b.name))
      .forEach((resort) => {
        const option = document.createElement("option");
        option.value = resort.id;
        option.textContent = `${resort.state} · ${resort.name}${resort.partner ? (isEnglish ? " (partner resort)" : "（合作雪场）") : ""}`;
        group.appendChild(option);
      });
    if (group.children.length) select.appendChild(group);
  });

  if ([...select.options].some((option) => option.value === current)) select.value = current;
};

window.populateStateSelect = function populateStateSelect(select) {
  if (!select) return;
  const isEnglish = window.SNOWLINK_LOCALE === "en";
  const states = [...new Set(window.SNOWLINK_RESORTS.flatMap((resort) => resort.state.split(" / ")))].sort();
  select.innerHTML = `<option value="all">${isEnglish ? "All states" : "全部州"}</option>`;
  states.forEach((state) => {
    const option = document.createElement("option");
    option.value = state;
    option.textContent = state;
    select.appendChild(option);
  });
};
